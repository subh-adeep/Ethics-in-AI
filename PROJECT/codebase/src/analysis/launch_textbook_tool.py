"""Launch the T3 textbook-evidence tool run: qwen + llama on Kaggle 2xT4, phi4 on AWS EC2.

    python launch_textbook_tool.py kaggle --mode smoke [--launch]
    python launch_textbook_tool.py ec2-bundle --mode smoke
    python launch_textbook_tool.py ec2-start                  # start instance, print IP
    python launch_textbook_tool.py ec2-deploy --mode smoke --ip X
    python launch_textbook_tool.py ec2-status --mode smoke --ip X
    python launch_textbook_tool.py ec2-fetch --mode smoke --ip X
    python launch_textbook_tool.py ec2-stop

EC2 cost control: the job runs under systemd, never at boot. When it ends (success,
error or time limit) the instance schedules its own poweroff in 10 minutes, which
leaves time to download results; a separate timer powers off after the hard limit.
The local controller stops the instance through the AWS API as soon as results are saved.
Kaggle lessons applied: kernel_type script, machine_shape NvidiaTeslaT4, pinned packages.
"""
