def kaggle(mode, launch):
    files = dict(source_files(), **run_files(mode))
    out_rel = t3.out_dir(mode).relative_to(PROJECT).as_posix()
    payload = dict(files=files, mode=mode, out=out_rel,
                   models={n: dict(repo=local.MODEL_IDS[n], revision=t3.REVISIONS[n]) for n in KAGGLE_MODELS})
    encoded = base64.b64encode(zlib.compress(json.dumps(payload, ensure_ascii=False).encode(), 9)).decode()
    source = BOOTSTRAP.format(mode=mode, payload=encoded, pins=PINS)
    compile(source, 'run_t3.py', 'exec')
    folder = PROJECT / f'kaggle/kernel_textbook_tool_{mode}'
    folder.mkdir(parents=True, exist_ok=True)
    (folder / 'run_t3.py').write_text(source, encoding='utf-8')
    slug, title = f'textbook-tool-{mode}-{t3.DATE}', f'Textbook Tool {mode.title()} {t3.DATE}'
    meta = dict(id=f'subhadeepsing/{slug}', title=title, code_file='run_t3.py', language='python',
                kernel_type='script', is_private=True, enable_gpu=True, enable_tpu=False, enable_internet=True,
                dataset_sources=[], competition_sources=[], kernel_sources=[], model_sources=[])
    (folder / 'kernel-metadata.json').write_text(json.dumps(meta, indent=2), encoding='utf-8')
    record = dict(at=pilot.now(), kernel=meta['id'], mode=mode, models=KAGGLE_MODELS,
                  source_sha256=pilot.sha(folder / 'run_t3.py'), bytes=len(source))
    if launch:
        from kaggle.api.kaggle_api_extended import KaggleApi
        from kagglesdk.kernels.types.kernels_api_service import ApiSaveKernelRequest
        from kagglesdk.kernels.types.kernels_enums import KernelExecutionType
        api = KaggleApi(); api.authenticate()
        req = ApiSaveKernelRequest()
        req.slug, req.new_title, req.text = meta['id'], title, source
        req.language, req.kernel_type, req.is_private = 'python', 'script', True
        req.enable_internet, req.enable_gpu, req.machine_shape = True, True, 'NvidiaTeslaT4'
        req.kernel_execution_type = KernelExecutionType.SAVE_AND_RUN_ALL
        with api.build_kaggle_client() as client:
            resp = client.kernels.kernels_api_client.save_kernel(req)
        if resp.error:
            raise RuntimeError(str(resp.error))
        record['response'] = resp.to_dict()
        pilot.atomic_json(t3.out_dir(mode) / 'kaggle_launch.json', record)
    print(json.dumps(record, indent=2, default=str))


# --------------------------------------------------------------------------- EC2
def unit(mode):
    limit = LIMITS[mode]
    out = f'{REMOTE}/PROJECT/codebase/results/textbook_tool_{mode}_{t3.DATE}/{EC2_MODEL}'
    cmd = (f'{VENV_PY} {REMOTE}/PROJECT/codebase/src/analysis/textbook_tool.py --worker --mode {mode} --gpu 0 '
           f'--model {EC2_MODEL} --model-root {EC2_MODEL_ROOT} --host AWS-EC2-g4dn.xlarge-T4')
    service = '\n'.join([
        '[Unit]', f'Description=T3 textbook tool {mode} ({EC2_MODEL})',
        'Wants=network-online.target', 'After=network-online.target',
        '[Service]', 'Type=exec', 'User=ubuntu', 'Group=ubuntu', f'WorkingDirectory={REMOTE}/PROJECT/codebase/src',
        'Environment=PYTHONUNBUFFERED=1', 'Environment=CUDA_VISIBLE_DEVICES=0', 'Environment=TOKENIZERS_PARALLELISM=false',
        'Environment=HF_HUB_OFFLINE=1', f'ExecStart={cmd}',
        f'ExecStopPost=+/usr/bin/python3 {REMOTE}/lifecycle.py finalize --output {out}',
        # Power off 10 minutes after the job ends, so results can be downloaded first.
        'ExecStopPost=+/usr/sbin/shutdown -P +10',
        f'RuntimeMaxSec={limit}', 'TimeoutStopSec=45', 'KillMode=control-group', 'Restart=no',
        f'StandardOutput=append:{out}/console.log', f'StandardError=append:{out}/console.log', ''])
    deadline_service = '\n'.join(['[Unit]', 'Description=T3 backup poweroff', '[Service]', 'Type=oneshot',
                                  'ExecStart=/usr/bin/systemctl --no-block poweroff', ''])
    timer = '\n'.join(['[Unit]', 'Description=T3 hard deadline: power off', '[Timer]',
                       f'OnActiveSec={limit // 60 + 20}min', 'AccuracySec=1s', 'Unit=ethics-t3-deadline.service', ''])
    install = f'''#!/bin/bash
set -euo pipefail
cd {REMOTE}
mkdir -p {out}
test -x {VENV_PY}
test -d {EC2_MODEL_ROOT}/models--unsloth--Phi-4-mini-instruct-bnb-4bit
sudo install -m 644 deployment/ethics-t3-{mode}.service deployment/ethics-t3-deadline.service deployment/ethics-t3-deadline.timer /etc/systemd/system/
sudo systemctl daemon-reload
sudo systemctl reset-failed ethics-t3-{mode}.service 2>/dev/null || true
sudo shutdown -c 2>/dev/null || true
sudo systemctl start ethics-t3-deadline.timer
sudo systemctl start ethics-t3-{mode}.service
echo T3_EC2_STARTED
'''
    return {f'deployment/ethics-t3-{mode}.service': service, 'deployment/ethics-t3-deadline.service': deadline_service,
            'deployment/ethics-t3-deadline.timer': timer, 'deployment/install.sh': install}


def ec2_bundle(mode):
    files = {f'PROJECT/{k}': v for k, v in dict(source_files(), **run_files(mode)).items()}
    files['lifecycle.py'] = (SRC / 'analysis/ec2_job_lifecycle.py').read_text(encoding='utf-8')
    files.update(unit(mode))
    path = t3.out_dir(mode) / 'ec2_bundle.tar.gz'
    with tarfile.open(path, 'w:gz') as archive:
        for name, text in files.items():
            data = text.encode('utf-8')
            info = tarfile.TarInfo(name); info.size = len(data); info.mode = 0o755 if name.endswith('.sh') else 0o644
            archive.addfile(info, io.BytesIO(data))
    print(path)
    return path


def aws(*args):
    return subprocess.run([*AWS, 'ec2', *args, '--region', REGION, '--output', 'json'],
                          check=True, capture_output=True, text=True).stdout


def state():
    data = json.loads(aws('describe-instances', '--instance-ids', INSTANCE))
    inst = data['Reservations'][0]['Instances'][0]
    return inst['State']['Name'], inst.get('PublicIpAddress')


def ssh_args(ip):
    known = KEY.parent / 'known_hosts_t3'  # no spaces: ssh splits this option on whitespace
    return ['-i', str(KEY), '-o', 'StrictHostKeyChecking=accept-new', '-o', f'UserKnownHostsFile={known}',
            '-o', 'ConnectTimeout=15', '-o', 'BatchMode=yes']


def ssh(ip, command, check=True):
    return subprocess.run([SSH, *ssh_args(ip), f'ubuntu@{ip}', command], capture_output=True, text=True, check=check)


def ec2_start():
    st, ip = state()
    if st == 'stopping':
        while st == 'stopping':
            time.sleep(10); st, ip = state()
    if st != 'running':
        aws('start-instances', '--instance-ids', INSTANCE)
        subprocess.run([*AWS, 'ec2', 'wait', 'instance-running', '--instance-ids', INSTANCE, '--region', REGION], check=True)
    st, ip = state()
    for _ in range(30):
        if ssh(ip, 'echo ok', check=False).returncode == 0:
            print(json.dumps(dict(state=st, ip=ip, ssh='ok')))
            return ip
        time.sleep(10)
    raise RuntimeError('SSH did not come up')


def ec2_deploy(mode, ip):
    bundle = ec2_bundle(mode)
    ssh(ip, f'rm -rf {REMOTE} && mkdir -p {REMOTE}')
    subprocess.run([SCP, *ssh_args(ip), bundle.name, f'ubuntu@{ip}:{REMOTE}/bundle.tar.gz'], check=True, cwd=bundle.parent)
    r = ssh(ip, f'cd {REMOTE} && tar xzf bundle.tar.gz && bash deployment/install.sh', check=False)
    print(r.stdout, r.stderr)
    if r.returncode:
        raise RuntimeError('Deploy failed')


def ec2_status(mode, ip):
    out = f'{REMOTE}/PROJECT/codebase/results/textbook_tool_{mode}_{t3.DATE}/{EC2_MODEL}'
    r = ssh(ip, f'systemctl is-active ethics-t3-{mode}.service; ls {out}; tail -3 {out}/console.log; '
                f'test -f {out}/completed.json && echo T3_DONE', check=False)
    print(r.stdout[-3000:], r.stderr[-500:])
    return r.stdout


def ec2_fetch(mode, ip):
    rel = f'PROJECT/codebase/results/textbook_tool_{mode}_{t3.DATE}/{EC2_MODEL}'
    dest = t3.out_dir(mode)
    ssh(ip, f'cd {REMOTE} && tar czf /tmp/t3_{mode}_{EC2_MODEL}.tar.gz {rel}')
    local_tar = dest / f'ec2_{EC2_MODEL}_results.tar.gz'
    subprocess.run([SCP, *ssh_args(ip), f'ubuntu@{ip}:/tmp/t3_{mode}_{EC2_MODEL}.tar.gz', local_tar.name], check=True, cwd=dest)
    with tarfile.open(local_tar) as archive:
        for member in archive.getmembers():
            if not member.isfile() or '..' in member.name:
                continue
            target = dest / EC2_MODEL / Path(member.name).relative_to(rel)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(archive.extractfile(member).read())
    print('fetched to', dest / EC2_MODEL)


def ec2_stop():
    aws('stop-instances', '--instance-ids', INSTANCE)
    print(json.dumps(dict(stop_requested=True, state=state()[0])))


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('action', choices=['kaggle', 'ec2-bundle', 'ec2-start', 'ec2-deploy', 'ec2-status', 'ec2-fetch', 'ec2-stop'])
    ap.add_argument('--mode', choices=['smoke', 'full'], default='smoke')
    ap.add_argument('--launch', action='store_true')
    ap.add_argument('--ip')
    a = ap.parse_args()
    if a.action == 'kaggle':
        kaggle(a.mode, a.launch)
    elif a.action == 'ec2-bundle':
        ec2_bundle(a.mode)
    elif a.action == 'ec2-start':
        ec2_start()
    elif a.action == 'ec2-deploy':
        ec2_deploy(a.mode, a.ip)
    elif a.action == 'ec2-status':
        ec2_status(a.mode, a.ip)
    elif a.action == 'ec2-fetch':
        ec2_fetch(a.mode, a.ip)
    else:
        ec2_stop()
