    out = project / p["out"]
    procs, threads = [], []

    def relay(proc, gpu, name):
        with (out / f"{{name}}_worker.log").open("a", encoding="utf-8") as log:
            for line in proc.stdout:
                log.write(line); log.flush()
                print(f"[GPU{{gpu}}/{{name}}] {{line.rstrip()}}", flush=True)

