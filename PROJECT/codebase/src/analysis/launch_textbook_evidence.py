"""Build and (optionally) launch the dual-T4 Kaggle job for textbook evidence.

    python launch_textbook_evidence.py --mode smoke            # build bundle only
    python launch_textbook_evidence.py --mode smoke --launch   # build + push to Kaggle

Lessons from earlier Kaggle runs applied here:
- kernel_type is "script" (ethics-tools-v2-full-phi4 failed when a .py was run as a notebook);
- machine_shape NvidiaTeslaT4 gives two T4 GPUs, and the job refuses to start with fewer;
- package pins match the versions that worked on 2xT4 / Python 3.13 (MedQA web + exact lookup runs).
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import zlib
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve()
PROJECT = HERE.parents[3]
MODULE = HERE.with_name("textbook_evidence.py")
ITEMS = PROJECT / "data/final/medqa_146_textbook_cohort.json"
DATE = "20261110"
MODES = {
    "setup": dict(limit=2, corpus_limit=5000, slug=f"textbook-evidence-setup-{DATE}", title=f"Textbook Evidence Setup {DATE}"),
    "smoke": dict(limit=10, slug=f"textbook-evidence-smoke-{DATE}", title=f"Textbook Evidence Smoke {DATE}"),
    "full": dict(limit=0, slug=f"textbook-evidence-full-{DATE}", title=f"Textbook Evidence Full {DATE}"),
}
PINS = ["transformers==5.17.0", "accelerate==1.15.0", "bitsandbytes==0.50.2", "bm25s==0.3.16"]

BOOTSTRAP = '''"""Kaggle bootstrap: textbook evidence selection ({mode}). Generated by launch_textbook_evidence.py."""
import base64, json, subprocess, sys, zlib
from pathlib import Path

PAYLOAD_B64 = "{payload}"


def main():
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", *{pins!r}], check=True)
    # Stemming is optional: BM25 still works without it if the wheel is unavailable.
    subprocess.run([sys.executable, "-m", "pip", "install", "-q", "PyStemmer"], check=False)
    p = json.loads(zlib.decompress(base64.b64decode(PAYLOAD_B64)))
    work = Path("/kaggle/working")
    src = work / "textbook_evidence.py"
    src.write_text(p["module"], encoding="utf-8")
    items = work / "medqa_items.json"
    items.write_text(json.dumps(p["items"], ensure_ascii=False), encoding="utf-8")
    out = work / p["out_name"]
    out.mkdir(parents=True, exist_ok=True)
    (out / "manifest.json").write_text(json.dumps(p["manifest"], indent=2), encoding="utf-8")
    cmd = [sys.executable, str(src), "--phase", "all", "--out", str(out), "--cache", "/tmp/te_cache",
           "--items", str(items), "--limit", str(p["limit"]), "--require-gpus", "2",
           "--corpus-limit", str(p.get("corpus_limit", 0))]
    print("RUN", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True)
    print("TEXTBOOK_EVIDENCE_COMPLETE", flush=True)


if __name__ == "__main__":
    main()
'''


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def bundle(mode: str) -> tuple[Path, dict]:
    cfg = MODES[mode]
    module = MODULE.read_text(encoding="utf-8")
    items = json.loads(ITEMS.read_text(encoding="utf-8"))
    out_name = f"textbook_evidence_{mode}_{DATE}"
    manifest = dict(at=datetime.now(timezone.utc).isoformat(), mode=mode, limit=cfg["limit"],
                    corpus_limit=cfg.get("corpus_limit", 0),
                    questions=cfg["limit"] or len(items), item_ids=[i["id"] for i in items][:cfg["limit"] or None],
                    module_sha256=sha(module.encode()), items_sha256=sha(ITEMS.read_bytes()), pins=PINS)
    payload = dict(module=module, items=items, limit=cfg["limit"], corpus_limit=cfg.get("corpus_limit", 0),
                   out_name=out_name, manifest=manifest)
    encoded = base64.b64encode(zlib.compress(json.dumps(payload).encode("utf-8"), 9)).decode()
    folder = PROJECT / "kaggle" / f"kernel_textbook_evidence_{mode}"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "run_textbook_evidence.py").write_text(
        BOOTSTRAP.format(mode=mode, payload=encoded, pins=PINS), encoding="utf-8")
    metadata = dict(id=f"subhadeepsing/{cfg['slug']}", title=cfg["title"], code_file="run_textbook_evidence.py",
                    language="python", kernel_type="script", is_private=True, enable_gpu=True, enable_tpu=False,
                    enable_internet=True, dataset_sources=[], competition_sources=[], kernel_sources=[],
                    model_sources=[])
    (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    results = PROJECT / "codebase/results" / out_name
    results.mkdir(parents=True, exist_ok=True)
    (results / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return folder, metadata


def launch(mode: str) -> None:
    folder, metadata = bundle(mode)
    from kaggle.api.kaggle_api_extended import KaggleApi
    from kagglesdk.kernels.types.kernels_api_service import ApiSaveKernelRequest
    from kagglesdk.kernels.types.kernels_enums import KernelExecutionType

    api = KaggleApi()
    api.authenticate()
    req = ApiSaveKernelRequest()
    req.slug = metadata["id"]
    req.new_title = metadata["title"]
    req.text = (folder / "run_textbook_evidence.py").read_text(encoding="utf-8")
    req.language = "python"
    req.kernel_type = "script"
    req.is_private = True
    req.enable_internet = True
    req.enable_gpu = True
    req.machine_shape = "NvidiaTeslaT4"
    req.kernel_execution_type = KernelExecutionType.SAVE_AND_RUN_ALL
    with api.build_kaggle_client() as client:
        resp = client.kernels.kernels_api_client.save_kernel(req)
    if resp.error:
        raise RuntimeError(str(resp.error))
    record = dict(at=datetime.now(timezone.utc).isoformat(), kernel=metadata["id"], mode=mode,
                  machine_shape="NvidiaTeslaT4", requested_gpus=2, response=resp.to_dict())
    out = PROJECT / "codebase/results" / f"textbook_evidence_{mode}_{DATE}" / "kaggle_launch.json"
    out.write_text(json.dumps(record, indent=2, default=str), encoding="utf-8")
    print(json.dumps(record, indent=2, default=str), flush=True)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=list(MODES), default="smoke")
    ap.add_argument("--launch", action="store_true")
    a = ap.parse_args()
    if a.launch:
        launch(a.mode)
    else:
        folder, meta = bundle(a.mode)
        print(json.dumps(dict(folder=str(folder), metadata=meta), indent=2))
